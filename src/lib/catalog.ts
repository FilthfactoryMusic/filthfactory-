function upcomingISO(daysFromTue: number, hour: number, minute: number) {
  // Anchor to Tue 1 Sep 2026 so the schedule is stable in this build.
  const base = Date.UTC(2026, 8, 1, 0, 0, 0);
  const d = new Date(base + daysFromTue * 86400000);
  d.setUTCHours(hour, minute, 0, 0);
  return d.toISOString();
}

