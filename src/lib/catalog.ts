export function relatedMixes(mix: Mix, n = 6) {
  return MIXES.filter(
    (m) => m.id !== mix.id && (m.djId === mix.djId || m.genres.some((g) => mix.genres.includes(g))),
  ).slice(0, n);
}

export function searchCatalog(q: string) {
  const s = q.trim().toLowerCase();
  if (!s) return { mixes: [] as Mix[], djs: [] as Dj[], live: [] as LiveShow[] };
  const hit = (parts: string[]) => parts.some((p) => p.toLowerCase().includes(s));
  return {
    mixes: [] as Mix[],
    djs: WORLD_DJS.filter((d) => hit([d.name, d.handle, d.city, d.show, d.genres.join(" "), d.bio])),
    live: WORLD_LIVE.filter((l) =>
      hit([l.title, l.venue, l.city, l.genres.join(" "), getDj(l.djId)?.name ?? ""]),
    ),
  };
}

export function liveOffsetSec(show: LiveShow) {
  if (show.status !== "live") return 0;
  const day = Math.floor(Date.now() / 86400000);
  const h = hashString(show.id + String(day));
  const max = Math.max(12, show.durationMin - 20);
  const startedAgoMin = 16 + (h % max);
  return Math.min(startedAgoMin * 60, (show.durationMin - 8) * 60);
}

export function currentTrack(tracklist: Track[], t: number) {
  if (!tracklist.length) return null;
  let cur = tracklist[0];
  for (const trk of tracklist) {
    if (trk.t <= t) cur = trk;
    else break;
  }
  return cur;
}

export function genreToEngine(genre: string): EngineGenre {
  const g = genre.toLowerCase();
  if (g.includes("garage") || g.includes("2-step") || g.includes("2 step")) return "ukg";
  if (g.includes("jungle")) return "jungle";
  if (g.includes("drum")) return "dnb";
  if (g.includes("grime") || g.includes("bass")) return "grime";
  if (g.includes("techno") && g.includes("industrial")) return "industrial";
  if (g.includes("industrial")) return "industrial";
  if (g.includes("techno")) return "techno";
  if (g.includes("disco")) return "disco";
  if (g.includes("funky")) return "funky";
  if (g.includes("bassline")) return "bassline";
  if (g.includes("break")) return "breaks";
  if (g.includes("electro")) return "electro";
  return "house";
}

